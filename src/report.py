"""Correlations and the README figure, from the pipeline's period table.

Reads only data/processed/final_all_combined.csv (committed), so it runs without the raw
data; CI regenerates docs/results.md and fails if any number in it changes.
"""

from pathlib import Path

from check_requirements import check_requirements

ROOT = Path(__file__).resolve().parents[1]
check_requirements(ROOT / "requirements.txt")

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

COMBINED = ROOT / "data" / "processed" / "final_all_combined.csv"
RESULTS = ROOT / "docs" / "results.md"
FIGURE = ROOT / "docs" / "figures" / "cases_vs_anxiety.png"

# (label, column in final_all_combined.csv, days column that turns it into a daily rate)
SERIES = [
    ('Adults with anxiety symptoms (mean of 51 state estimates)', 'Value', None),
    ('Adults with anxiety symptoms (CDC national estimate)', 'NationalValue', None),
    ('Instagram likes', 'InstagramLikes', 'SocialDays'),
    ('Instagram posts in the dataset', 'InstagramPosts', 'SocialDays'),
    ('Instagram likes per post', None, None),
    ('@TheEconomist retweets', 'EconRetweets', 'SocialDays'),
    ('@TheEconomist likes', 'EconLikes', 'SocialDays'),
]


def survey_periods(df):
    """Drop period -1 (everything before the survey started)."""
    return df[df['TimePeriod'] > 0].set_index('TimePeriod')


def pearson(x, y):
    ok = x.notna() & y.notna()
    return np.corrcoef(x[ok], y[ok])[0, 1], int(ok.sum())


def correlations(df):
    """Rows of (label, n, r on totals, r per day, r on changes between periods) against new cases."""
    p = survey_periods(df)
    cases_per_day = p['PositiveCases'] / p['PeriodDays']
    rows = []
    for label, col, days in SERIES:
        if col is None:  # likes per post: already a rate, no total to compare
            r_total, per_day = None, p['InstagramLikes'] / p['InstagramPosts']
        else:
            r_total = pearson(p[col], p['PositiveCases'])[0]
            per_day = p[col] / p[days] if days else p[col]  # survey percentages are not divided
        r_day, n = pearson(per_day, cases_per_day)
        r_diff = pearson(per_day.diff(), cases_per_day.diff())[0]
        rows.append((label, n, r_total, r_day, r_diff))
    return rows


def render_results(df):
    p = survey_periods(df)
    fmt = lambda r: '' if r is None else f'{r:.3f}'.replace('-', '−')
    lines = [
        '# Results',
        '',
        'Generated by `src/report.py` from `data/processed/final_all_combined.csv`. Do not edit by hand.',
        '',
        f'Pearson r with new COVID-19 cases across the {len(p)} survey periods that overlap the social-media data. '
        f'Periods last {int(p.PeriodDays.min())} to {int(p.PeriodDays.max())} days, so totals partly measure period '
        'length; "per day" divides cases by `PeriodDays` and social counts by `SocialDays`. '
        '"Changes" correlates the per-day values\' change from one period to the next, which removes most of the shared trend.',
        '',
        '| Series | Periods | Totals | Per day | Changes between periods |',
        '|---|---|---|---|---|',
    ]
    lines += [f'| {label} | {n} | {fmt(t)} | {fmt(d)} | {fmt(c)} |' for label, n, t, d, c in correlations(df)]
    cases = p['PositiveCases']
    rho = cases.rank().corr(p['Value'].rank())  # Spearman; pandas 2 needs scipy for method='spearman'
    lines += [
        '',
        f'Spearman rank correlation, cases vs. the state-mean anxiety series (totals): {fmt(rho)}.',
        '',
        f'New cases in these periods: {cases.sum():,.0f}. '
        f'Instagram posts per day: {p.InstagramPosts.iloc[0] / p.SocialDays.iloc[0]:.0f} in period 1, '
        f'{(p.InstagramPosts / p.SocialDays).max():.0f} at the most.',
        '',
    ]
    return '\n'.join(lines)


def plot(df, path):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt

    p = survey_periods(df)
    cases_per_day = p['PositiveCases'] / p['PeriodDays'] / 1000
    r = pearson(p['Value'], cases_per_day)[0]
    fig, ax = plt.subplots(figsize=(9, 4.2), dpi=150)
    ax.bar(p.index, cases_per_day, color='#9db3d1', label='New COVID-19 cases per day (thousands)')
    ax.set_xlabel('CDC Household Pulse survey period (Apr 2020 – Feb 2021 overlap)')
    ax.set_ylabel('New cases per day (thousands)')
    ax2 = ax.twinx()
    ax2.plot(p.index, p['Value'], color='#b5384b', marker='o', lw=2, label='Adults with anxiety symptoms (%)')
    ax2.set_ylabel('Anxiety symptoms (% of adults, state mean)')
    for a in (ax, ax2):
        a.spines['top'].set_visible(False)
    handles = ax.get_legend_handles_labels()[0] + ax2.get_legend_handles_labels()[0]
    ax.legend(handles, [h.get_label() for h in handles], loc='upper left', frameon=False, fontsize=8)
    ax.set_title(f'New COVID-19 cases per day vs. reported anxiety symptoms (Pearson r = {r:.2f}, n = {len(p)} periods)',
                 fontsize=10, loc='left')
    fig.tight_layout()
    fig.savefig(path, metadata={'Software': None})
    plt.close(fig)


def main():
    df = pd.read_csv(COMBINED)
    RESULTS.write_text(render_results(df), encoding='utf-8', newline='\n')
    FIGURE.parent.mkdir(parents=True, exist_ok=True)
    plot(df, FIGURE)
    print(f'Wrote {RESULTS.relative_to(ROOT)} and {FIGURE.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
